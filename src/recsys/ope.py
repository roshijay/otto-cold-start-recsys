"""Off-policy evaluation: should we ship co-visitation over popularity?

HONEST SETUP -- read before the code: OTTO's logs were NOT generated by a known
randomized policy, so true propensities are unknowable. We SIMULATE logging
policies over our test sessions instead. Everything below estimates performance
in that simulated world: directional evidence for prioritizing engineering work,
NOT a substitute for a live experiment.

Two attempts, one script:
- Attempt 1 (alpha=0.0): pure popularity logger. Result: 4/40,000 impressions
  matched the held-out item -- no effective overlap between a popularity logger
  and long-tail truth. Both estimators starved; the eval is uninformative.
  (Kept in the writeup as the diagnostic: this is what no-overlap looks like.)
- Attempt 2 (alpha=0.5): 50/50 PILOT mixture of popularity logger + candidate.
  This is the realistic OPE setting -- pilot logs are where OPE actually gets
  used -- and mixture logging bounds every importance weight by 1/alpha = 2,
  collapsing the variance by design.

Policies:
- pi_pop: softmax over popularity scores (1/5/20 weights); temperature SOLVED
  (tau0=895.3) so the top-100 items get exactly 80% of impressions.
- pi_cand: epsilon-greedy (eps=0.05) over co-visitation top-20, the Phase 4 winner.
  (Spec said item2vec; the bake-off changed the ship candidate.)
- pi_log = (1-alpha)*pi_pop + alpha*pi_cand. All propensities exact by construction.

Estimators (per alpha): IPS and doubly robust for BOTH policies off the same log
(OPE can evaluate many policies from one log), reward model = global empirical
mean reward per item (context-free), 1000-replicate bootstrap CIs on the lift.
"""
import json
import time

import duckdb
import numpy as np

from evaluate import load_sessions, time_split, K
from models import recommend_covisit, build_covisit

EPS = 0.05    # exploration rate of the candidate policy
N_BOOT = 1000  # bootstrap replicates for the CI
SEED = 42
REWARD_W = {"clicks": 0.1, "carts": 0.3, "orders": 1.0}  # multi-objective, per spec
ALPHAS = [0.0, 0.5]  # attempt 1: pure popularity log; attempt 2: 50/50 pilot


def popularity_scores():
    """Item universe + weighted popularity scores, read from the mart."""
    con = duckdb.connect("data/warehouse.duckdb", read_only=True)
    rows = con.execute(
        "select aid, n_clicks, n_carts, n_orders from main_marts.fct_item_stats"
    ).fetchall()
    con.close()
    aids = np.array([r[0] for r in rows])
    scores = np.array([r[1] + 5 * r[2] + 20 * r[3] for r in rows], dtype=float)
    return aids, scores


def solve_temperature(scores, topk=100, target_share=0.8):
    """Binary-search tau so the top-`topk` scores get `target_share` of softmax mass.

    Specify BEHAVIOR ("top-100 gets 80%"), solve for the knob -- no magic numbers.
    """
    s = np.sort(scores)[::-1] - scores.max()  # stability shift; order-preserving
    def topk_share(tau):
        e = np.exp(s / tau)
        return e[:topk].sum() / e.sum()
    lo, hi = 1e-3, 1e9  # share(lo)->~1 > target; share(hi)->topk/V < target
    for _ in range(80):
        mid = (lo + hi) / 2
        if topk_share(mid) > target_share:
            lo = mid   # too concentrated -> raise temperature
        else:
            hi = mid
    return (lo + hi) / 2


def run_alpha(alpha, inputs, held, held_w, aids, p0, topk, rec_sets, V, aid_to_idx):
    """Simulate one log with pilot fraction `alpha`; estimate both policies."""
    rng = np.random.default_rng(SEED + int(alpha * 100))
    n = len(inputs)

    # Sample the log: pilot-component from pi_cand, rest from pi_pop (vectorized).
    is_pilot = rng.random(n) < alpha
    pop_sample = aids[rng.choice(V, size=n, p=p0)]
    logged_aid = np.empty(n, dtype=np.int64)
    p_cand_of_logged = np.empty(n)  # pi_cand(a_i | x_i), exact either way
    for i in range(n):
        recs, rset = topk[i], rec_sets[i]
        k = len(recs)
        if is_pilot[i]:
            if k > 0 and rng.random() < 1 - EPS:
                a = recs[rng.integers(0, k)]          # exploit: uniform over top-K
            else:
                while True:                            # explore: uniform over rest
                    a = int(aids[rng.integers(0, V)])
                    if a not in rset:
                        break
            logged_aid[i] = a
        else:
            logged_aid[i] = pop_sample[i]
        if k == 0:
            p_cand_of_logged[i] = 1.0 / V
        elif int(logged_aid[i]) in rset:
            p_cand_of_logged[i] = (1 - EPS) / k
        else:
            p_cand_of_logged[i] = EPS / (V - k)

    logged_idx = np.array([aid_to_idx[int(a)] for a in logged_aid])
    p_pop_logged = p0[logged_idx]
    p_log = (1 - alpha) * p_pop_logged + alpha * p_cand_of_logged  # mixture propensity
    reward = np.where(logged_aid == held, held_w, 0.0)

    # Reward model: global empirical mean reward per item, fit on THIS log.
    # Context-free; DR stays unbiased because propensities are exact.
    r_hat = np.zeros(V)
    for h, hw in zip(held, held_w):
        j = aid_to_idx.get(int(h))
        if j is not None:
            r_hat[j] += hw
    r_hat /= n
    R_pop = float(p0 @ r_hat)  # E_{pi_pop}[r_hat] -- context-free, computed once
    total_r = r_hat.sum()
    R_cand = np.empty(n)       # E_{pi_cand}[r_hat(x)] -- exact via top-K + totals
    for i, recs in enumerate(topk):
        k = len(recs)
        if k == 0:
            R_cand[i] = total_r / V
        else:
            s_top = sum(r_hat[aid_to_idx[a]] for a in recs)
            R_cand[i] = (1 - EPS) / k * s_top + EPS / (V - k) * (total_r - s_top)

    # IPS + DR for both policies off the same log.
    w_pop = p_pop_logged / p_log
    w_cand = p_cand_of_logged / p_log
    ips_pop_i = w_pop * reward
    ips_cand_i = w_cand * reward
    dr_pop_i = R_pop + w_pop * (reward - r_hat[logged_idx])
    dr_cand_i = R_cand + w_cand * (reward - r_hat[logged_idx])

    lift_ips_i = ips_cand_i - ips_pop_i
    lift_dr_i = dr_cand_i - dr_pop_i
    boot = np.empty((N_BOOT, 2))
    for b in range(N_BOOT):
        idx = rng.integers(0, n, n)  # resample sessions with replacement
        boot[b, 0] = lift_ips_i[idx].mean()
        boot[b, 1] = lift_dr_i[idx].mean()

    return {
        "alpha": alpha,
        "n": n,
        "n_matches": int((reward > 0).sum()),
        "V_pi_pop_ips": float(ips_pop_i.mean()),
        "V_pi_cand_ips": float(ips_cand_i.mean()),
        "V_pi_pop_dr": float(dr_pop_i.mean()),
        "V_pi_cand_dr": float(dr_cand_i.mean()),
        "lift_ips": float(lift_ips_i.mean()),
        "lift_ips_ci95": [float(x) for x in np.percentile(boot[:, 0], [2.5, 97.5])],
        "lift_dr": float(lift_dr_i.mean()),
        "lift_dr_ci95": [float(x) for x in np.percentile(boot[:, 1], [2.5, 97.5])],
        "max_weight": float(np.maximum(w_pop, w_cand).max()),
    }


def main():
    t0 = time.time()
    sessions = load_sessions()
    train, test = time_split(sessions)
    test = [s for s in test if len(s[1]) >= 2]
    inputs = [s[1][:-1] for s in test]
    held = np.array([s[1][-1] for s in test])
    held_w = np.array([REWARD_W[s[2][-1]] for s in test])
    print(f"test sessions: {len(test):,}", flush=True)

    aids, scores = popularity_scores()
    V = len(aids)
    aid_to_idx = {int(a): i for i, a in enumerate(aids)}
    tau0 = solve_temperature(scores)
    p0 = np.exp((scores - scores.max()) / tau0)
    p0 /= p0.sum()
    print(f"tau0 = {tau0:.1f}, action space = {V:,}", flush=True)

    build_covisit(train)
    topk = [recommend_covisit(a, K) for a in inputs]
    rec_sets = [set(r) for r in topk]
    print("candidate top-K built", flush=True)

    out = {}
    for alpha in ALPHAS:
        print(f"--- alpha = {alpha} ---", flush=True)
        res = run_alpha(alpha, inputs, held, held_w, aids, p0, topk, rec_sets,
                        V, aid_to_idx)
        out[str(alpha)] = res
        print(json.dumps(res, indent=1), flush=True)

    with open("docs/ope-numbers.json", "w") as f:
        json.dump(out, f, indent=1)
    print(f"total: {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
